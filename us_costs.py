# -*- coding: utf-8 -*-
"""미장 거래비용 — **계좌 체결 데이터로 실측한 값.** 추정·블로그 인용 금지.

━━━ 왜 이 파일이 있나 ━━━
비용을 세 번 틀렸다.
  1. "$10 이하 주문은 수수료 무료" — 블로그를 근거로 말했다. **틀렸다.**
     그건 토스의 별개 서비스('주식 모으기', 적립식 매수) 조건이고 API 주문은 아니다.
  2. 보유 현황의 `cost.commission = $0.04` 를 보고 "건당 최소 수수료 $0.04,
     따라서 $7 슬롯은 0.57% 로 3배 비싸다"고 했다. **틀렸다.** 그 값은 왕복
     예상치를 미리 표시한 것이고, 체결 수수료는 $0.02 였다.
  3. 그래서 "슬롯 10 이 비용 때문에 불리할 수 있다"고 경고했다. **반대였다.**

결론: `/api/v1/orders/{id}` 의 `execution.commission` / `execution.tax` 를 본다.
그게 실제로 뗀 금액이다.

━━━ 실측 (2026-09-30, 우리 계좌) ━━━
    매수 $24.13  수수료 $0.02  세금 $0      → 0.083%
    매도 $21.86  수수료 $0.02  세금 $0.01   → 0.137%
    매도 $0.074  수수료 $0     세금 $0.01   → 세금 하한 $0.01 확인

구조:
  · **수수료 0.1%, 센트 미만 절사.** $10 미만 주문은 0.1% 가 $0.01 밑이라
    절사되어 **실질 0원**이 된다(무료 이벤트가 아니라 절사의 결과다).
  · **세금은 매도에만, 최소 $0.01.** 미국 SEC fee 다. 금액이 작을수록 비율이 커진다.

━━━ 슬롯 크기별 왕복 비용 ━━━
    슬롯 $24 → 0.22%    (백테스트 가정 0.20% 와 거의 같음)
    슬롯 $10 → 0.10%
    슬롯  $7 → 0.14%    ← 지금. 슬롯3 시절보다 **더 싸다**
    슬롯  $5 → 0.20%
    슬롯  $3 → 0.33%    ← 여기서부터 백테스트 가정보다 비싸진다
    슬롯  $2 → 0.50%

**슬롯 하한 $5.** 세금 하한 $0.01 이 고정비라, 슬롯이 작아질수록 비용률이 커진다.
자산이 줄면 슬롯 수를 줄여 슬롯 금액을 $5 이상으로 유지해야 한다.

사용: python3 us_costs.py
"""
COMMISSION_RATE = 0.001     # 편도. 센트 미만 절사
TAX_MIN_USD = 0.01          # 매도 시 SEC fee 하한
MIN_SLOT_USD = 5.0          # 이보다 작아지면 비용률이 백테스트 가정을 넘는다


def round_trip_pct(slot_usd):
    """슬롯 금액에 대한 왕복 비용률(%). 절사·하한을 그대로 반영한다."""
    buy_fee = int(slot_usd * COMMISSION_RATE * 100) / 100      # 센트 미만 절사
    sell_fee = int(slot_usd * COMMISSION_RATE * 100) / 100
    tax = max(TAX_MIN_USD, 0.0)
    return (buy_fee + sell_fee + tax) / slot_usd * 100


def max_slots(equity_usd):
    """슬롯 금액이 하한($5) 이상이 되도록 하는 최대 슬롯 수."""
    return max(1, int(equity_usd // MIN_SLOT_USD))


def main():
    print("  슬롯 금액별 왕복 비용 (실측 구조 반영)")
    print(f"  {'슬롯$':>7}{'매수':>8}{'매도':>8}{'세금':>8}{'왕복%':>8}")
    for s in (2, 3, 5, 7, 10, 24, 50):
        buy = int(s * COMMISSION_RATE * 100) / 100
        print(f"  {s:>7}{buy:>8.2f}{buy:>8.2f}{TAX_MIN_USD:>8.2f}"
              f"{round_trip_pct(s):>8.2f}")
    print(f"\n  백테스트 가정 0.20% | 슬롯 하한 ${MIN_SLOT_USD:.0f}")
    for eq in (72.5, 50, 30, 20):
        print(f"  자산 ${eq:>5.1f} → 최대 슬롯 {max_slots(eq)}개 "
              f"(슬롯 ${eq/max_slots(eq):.2f}, 왕복 {round_trip_pct(eq/max_slots(eq)):.2f}%)")


if __name__ == "__main__":
    main()
